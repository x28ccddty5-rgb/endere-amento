DO $preflight$
DECLARE
  v_administrator_count integer;
  v_unknown_role_count integer;
  v_profile_columns_count integer;
BEGIN
  IF pg_catalog.to_regclass('public.profiles') IS NULL THEN
    RAISE EXCEPTION 'PERMISSION_PREFLIGHT_PROFILES_TABLE_MISSING';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'anon')
     OR NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname = 'authenticated') THEN
    RAISE EXCEPTION 'PERMISSION_PREFLIGHT_SUPABASE_ROLES_MISSING: expected anon and authenticated roles';
  END IF;

  IF pg_catalog.to_regprocedure('auth.uid()') IS NULL THEN
    RAISE EXCEPTION 'PERMISSION_PREFLIGHT_AUTH_UID_MISSING: expected auth.uid() in the isolated Supabase-compatible database';
  END IF;

  SELECT pg_catalog.count(*) INTO v_profile_columns_count
  FROM information_schema.columns
  WHERE table_schema = 'public' AND table_name = 'profiles'
    AND column_name IN ('id', 'role', 'username', 'name');
  IF v_profile_columns_count <> 4 THEN
    RAISE EXCEPTION 'PERMISSION_PREFLIGHT_PROFILE_COLUMNS_MISSING: expected id, role, username, name';
  END IF;

  SELECT count(*) FILTER (WHERE pg_catalog.lower(pg_catalog.btrim(role)) = 'administrador'),
         count(*) FILTER (WHERE pg_catalog.lower(pg_catalog.btrim(role)) NOT IN
           ('administrador', 'lideranca', 'apoio', 'producao', 'visualizador'))
    INTO v_administrator_count, v_unknown_role_count
    FROM public.profiles;

  IF v_administrator_count < 1 THEN
    RAISE EXCEPTION 'PERMISSION_PREFLIGHT_NO_ADMINISTRATOR';
  END IF;
  -- Legacy Liderança profiles may remain during the transition. They receive no
  -- base matrix rows or individual overrides in this version, and the new helper
  -- explicitly denies them. Do not delete or rewrite these profiles in this migration.
  IF v_unknown_role_count > 0 THEN
    RAISE EXCEPTION 'PERMISSION_PREFLIGHT_UNKNOWN_PROFILE_ROLES: %', v_unknown_role_count;
  END IF;
END;
$preflight$;

CREATE TABLE public.permission_catalog (
  permission_key text PRIMARY KEY,
  module_name text NOT NULL,
  label text NOT NULL,
  description text NOT NULL,
  risk_level text NOT NULL CHECK (risk_level IN ('low', 'medium', 'high', 'critical')),
  is_admin_only boolean NOT NULL DEFAULT FALSE,
  user_override_allowed boolean NOT NULL DEFAULT TRUE,
  is_active boolean NOT NULL DEFAULT TRUE,
  sort_order integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT pg_catalog.transaction_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT pg_catalog.transaction_timestamp(),
  CONSTRAINT permission_catalog_key_format CHECK (permission_key ~ '^[a-z][a-z0-9_.]*$'),
  CONSTRAINT permission_catalog_no_admin_override CHECK (NOT (is_admin_only AND user_override_allowed))
);

CREATE TABLE public.role_permissions (
  role text NOT NULL CHECK (role IN ('administrador', 'apoio', 'producao', 'visualizador')),
  permission_key text NOT NULL REFERENCES public.permission_catalog(permission_key) ON UPDATE RESTRICT ON DELETE RESTRICT,
  allowed boolean NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT pg_catalog.transaction_timestamp(),
  updated_by uuid NULL REFERENCES public.profiles(id) ON DELETE SET NULL,
  PRIMARY KEY (role, permission_key)
);

CREATE TABLE public.user_permission_overrides (
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  permission_key text NOT NULL REFERENCES public.permission_catalog(permission_key) ON UPDATE RESTRICT ON DELETE RESTRICT,
  decision text NOT NULL CHECK (decision IN ('allow', 'deny')),
  updated_at timestamptz NOT NULL DEFAULT pg_catalog.transaction_timestamp(),
  updated_by uuid NULL REFERENCES public.profiles(id) ON DELETE SET NULL,
  PRIMARY KEY (user_id, permission_key)
);

CREATE INDEX user_permission_overrides_permission_key_idx
  ON public.user_permission_overrides (permission_key);

CREATE TABLE public.permission_change_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id uuid NULL UNIQUE,
  actor_id uuid NULL REFERENCES public.profiles(id) ON DELETE SET NULL,
  actor_username text NOT NULL,
  actor_role text NOT NULL,
  target_type text NOT NULL CHECK (target_type IN ('role', 'user')),
  target_role text NULL CHECK (target_role IS NULL OR target_role IN ('administrador', 'apoio', 'producao', 'visualizador')),
  target_user_id uuid NULL REFERENCES public.profiles(id) ON DELETE SET NULL,
  target_snapshot jsonb NULL,
  changes jsonb NOT NULL CHECK (pg_catalog.jsonb_typeof(changes) = 'array' AND pg_catalog.jsonb_array_length(changes) > 0),
  created_at timestamptz NOT NULL DEFAULT pg_catalog.transaction_timestamp(),
  CONSTRAINT permission_change_audit_target_shape CHECK (
    (target_type = 'role' AND target_role IS NOT NULL AND target_user_id IS NULL)
    OR (target_type = 'user' AND target_role IS NULL AND target_snapshot IS NOT NULL)
  )
);

CREATE INDEX permission_change_audit_created_at_idx
  ON public.permission_change_audit (created_at DESC);
CREATE INDEX permission_change_audit_actor_id_idx
  ON public.permission_change_audit (actor_id, created_at DESC);

