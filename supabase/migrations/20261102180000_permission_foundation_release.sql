-- Contract check: 29 active permissions x 4 active roles = 116 explicit base grants.
DO $contract$
DECLARE
  v_catalog integer;
  v_role_rows integer;
  v_distinct_role_rows integer;
BEGIN
  SELECT pg_catalog.count(*) INTO v_catalog FROM public.permission_catalog WHERE is_active;
  SELECT pg_catalog.count(*), pg_catalog.count(DISTINCT (role, permission_key))
    INTO v_role_rows, v_distinct_role_rows FROM public.role_permissions;
  IF v_catalog <> 29 OR v_role_rows <> 116 OR v_distinct_role_rows <> 116 THEN
    RAISE EXCEPTION 'PERMISSION_SEED_COUNT_MISMATCH: catalog %, role rows %, distinct rows %', v_catalog, v_role_rows, v_distinct_role_rows;
  END IF;
END;
$contract$;

COMMIT;
